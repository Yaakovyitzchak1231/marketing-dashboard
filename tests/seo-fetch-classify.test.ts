import { describe, expect, it } from 'vitest'
import { classifyFetch } from '@/lib/seo/fetch-classify'
import { WALL, page } from './helpers/seo-fake-web'

const H = (h: Record<string, string>) => h
const SITEMAP = '<?xml version="1.0"?><sitemapindex><sitemap><loc>https://tapdash.co/page-sitemap.xml</loc></sitemap></sitemapindex>'

describe('classifyFetch: why a fetch did or did not give us the page', () => {
  it('a normal 200 sitemap is ok', () => {
    const v = classifyFetch({ status: 200, body: SITEMAP, headers: H({ 'content-type': 'application/xml', server: 'cloudflare' }) })
    expect(v).toMatchObject({ status: 'ok', kind: 'ok', http_status: 200 })
  })

  it('a normal page that loads Cloudflare bot scripts is still ok', () => {
    const body = page({ title: 'Home' }).replace('</body>', '<script src="/cdn-cgi/challenge-platform/scripts/jsd/main.js"></script></body>')
    expect(classifyFetch({ status: 200, body, headers: H({ server: 'cloudflare', 'cf-ray': 'abc' }) }).status).toBe('ok')
  })

  it('SiteGround: HTTP 202 + sgcaptcha meta refresh (what tapdash.co answers cloud IPs)', () => {
    const v = classifyFetch({ status: 202, body: WALL, headers: H({ server: 'cloudflare', 'sg-captcha': 'challenge' }) })
    expect(v).toMatchObject({ status: 'blocked', kind: 'bot_protection', provider: 'SiteGround', http_status: 202 })
    expect(v.reason).toBe('Blocked: SiteGround captcha (HTTP 202)')
  })

  it('SiteGround: the challenge text alone, and the header alone, are recognised', () => {
    expect(classifyFetch({ status: 200, body: '<html><title>x</title>Checking the site connection security</html>' }).provider).toBe('SiteGround')
    expect(classifyFetch({ status: 403, body: '', headers: H({ 'sg-captcha': 'block' }) }).reason).toBe('Blocked: SiteGround captcha (HTTP 403)')
  })

  it('Cloudflare challenge ("Just a moment...", cf-chl, cf-mitigated)', () => {
    const body = '<!DOCTYPE html><html><head><title>Just a moment...</title></head><body><script>window._cf_chl_opt={}</script></body></html>'
    const v = classifyFetch({ status: 403, body, headers: H({ server: 'cloudflare', 'cf-mitigated': 'challenge' }) })
    expect(v).toMatchObject({ status: 'blocked', kind: 'bot_protection', provider: 'Cloudflare' })
    expect(v.reason).toBe('Blocked: Cloudflare challenge (HTTP 403)')
    expect(classifyFetch({ status: 503, body, headers: H({}) }).reason).toBe('Blocked: Cloudflare challenge (HTTP 503)')
  })

  it('Cloudflare firewall block page (error 1020)', () => {
    const body = '<html><head><title>Attention Required! | Cloudflare</title></head><body>Sorry, you have been blocked. Cloudflare Ray ID: 8f</body></html>'
    expect(classifyFetch({ status: 403, body }).reason).toBe('Blocked: Cloudflare firewall block (HTTP 403)')
  })

  it('other vendors are named from headers, cookies and body', () => {
    expect(classifyFetch({ status: 403, body: 'Access Denied', headers: H({ 'x-sucuri-id': '1', 'x-sucuri-block': 'BL' }) }).provider).toBe('Sucuri')
    expect(classifyFetch({ status: 403, body: '<html>Request unsuccessful. Incapsula incident ID: 1</html>' }).provider).toBe('Imperva')
    expect(classifyFetch({ status: 403, body: '{"url":"https://geo.captcha-delivery.com/captcha/"}', headers: H({ 'x-datadome': 'protected' }) }).provider).toBe('DataDome')
    expect(classifyFetch({ status: 403, body: '<div id="px-captcha"></div>' }).provider).toBe('PerimeterX')
    expect(classifyFetch({ status: 403, body: '<H1>Access Denied</H1> Reference #18.1f2e', headers: H({ server: 'AkamaiGHost' }) }).provider).toBe('Akamai')
    expect(classifyFetch({ status: 405, body: '', headers: H({ 'x-amzn-waf-action': 'captcha' }) }).provider).toBe('AWS WAF')
    expect(classifyFetch({ status: 403, body: 'Your access to this site has been limited by the site owner. Generated by Wordfence' }).provider).toBe('Wordfence')
  })

  it('a generic captcha page is blocked, with no vendor named', () => {
    const v = classifyFetch({ status: 403, body: '<html><title>Security check</title>Please complete the hCaptcha to continue</html>' })
    expect(v).toMatchObject({ status: 'blocked', kind: 'bot_protection', provider: null })
    expect(v.reason).toBe('Blocked: bot protection captcha (HTTP 403)')
  })

  it('plain 403 without captcha markers: access denied, with the page words as evidence', () => {
    const v = classifyFetch({ status: 403, body: '<html><head><title>403 Forbidden</title></head><body>Forbidden</body></html>' })
    expect(v).toMatchObject({ status: 'blocked', kind: 'access_denied', http_status: 403, provider: null })
    expect(v.reason).toBe('Blocked: server refused access (HTTP 403)')
    expect(v.detail).toContain('403 Forbidden')
  })

  it('login required: 401, or a redirect to a login page', () => {
    expect(classifyFetch({ status: 401, body: '', headers: H({ 'www-authenticate': 'Basic realm="x"' }) })).toMatchObject({ status: 'blocked', kind: 'login_required', reason: 'Blocked: login required (HTTP 401)' })
    const v = classifyFetch({ status: 200, body: page({ title: 'Log In' }), finalUrl: 'https://a.test/wp-login.php?redirect_to=x', requestedUrl: 'https://a.test/jewelers/' })
    expect(v).toMatchObject({ status: 'blocked', kind: 'login_required', reason: 'Blocked: login required (redirected to /wp-login.php)' })
  })

  it('rate limited: 429 with Retry-After in seconds or as a date', () => {
    expect(classifyFetch({ status: 429, body: '', headers: H({ 'retry-after': '60' }) }).reason).toBe('Rate limited (HTTP 429, retry in 60s)')
    const now = new Date('2026-10-13T01:00:00Z')
    expect(classifyFetch({ status: 429, body: '', headers: H({ 'retry-after': 'Tue, 13 Oct 2026 01:05:00 GMT' }) }, now).reason).toBe('Rate limited (HTTP 429, retry in 5 min)')
    expect(classifyFetch({ status: 429, body: '' }).reason).toBe('Rate limited (HTTP 429)')
  })

  it('geo-blocked: 451, or 403 with geo wording', () => {
    expect(classifyFetch({ status: 451, body: '' })).toMatchObject({ status: 'blocked', kind: 'geo_blocked', reason: "Blocked: not available in the checker's region (HTTP 451)" })
    expect(classifyFetch({ status: 403, body: 'This content is not available in your country.' }).kind).toBe('geo_blocked')
  })

  it('server errors and maintenance are errors, not fails', () => {
    expect(classifyFetch({ status: 500, body: '<title>Error</title>' })).toMatchObject({ status: 'error', kind: 'server_error', reason: 'Server error: internal server error (HTTP 500)' })
    expect(classifyFetch({ status: 502, body: '' }).reason).toBe('Server error: bad gateway (HTTP 502)')
    expect(classifyFetch({ status: 503, body: 'Briefly unavailable for scheduled maintenance. Check back in a minute.' })).toMatchObject({ status: 'error', kind: 'maintenance', reason: 'Site in maintenance mode (HTTP 503)' })
  })

  it('network failures: timeout, DNS, TLS, refused, reset, redirects', () => {
    const fetchFailed = (code: string, message = '') => Object.assign(new TypeError('fetch failed'), { cause: Object.assign(new Error(message || code), { code }) })
    const timeout = Object.assign(new Error('The operation was aborted due to timeout'), { name: 'TimeoutError' })
    expect(classifyFetch({ status: null, error: timeout, timeoutMs: 15000 })).toMatchObject({ status: 'error', kind: 'timeout', reason: "Couldn't reach: timed out after 15s" })
    expect(classifyFetch({ status: null, error: fetchFailed('ENOTFOUND', 'getaddrinfo ENOTFOUND nope.test') })).toMatchObject({ kind: 'dns', reason: "Couldn't reach: DNS lookup failed (the domain didn't resolve)" })
    expect(classifyFetch({ status: null, error: fetchFailed('CERT_HAS_EXPIRED', 'certificate has expired') }).kind).toBe('tls')
    expect(classifyFetch({ status: null, error: fetchFailed('ECONNREFUSED') }).reason).toBe("Couldn't reach: connection refused")
    expect(classifyFetch({ status: null, error: fetchFailed('ECONNRESET') }).kind).toBe('connection_reset')
    expect(classifyFetch({ status: null, error: Object.assign(new TypeError('fetch failed'), { cause: new Error('redirect count exceeded') }) }).reason).toBe("Couldn't reach: too many redirects")
  })

  it('a real 404/410 is "missing" — the one genuine fix', () => {
    expect(classifyFetch({ status: 404, body: page({ title: 'Page not found' }) })).toMatchObject({ status: 'missing', kind: 'not_found', reason: 'Not found (HTTP 404)' })
    expect(classifyFetch({ status: 410, body: '' }).status).toBe('missing')
  })

  it('anything else names the status and the page words, never a blank reason', () => {
    const v = classifyFetch({ status: 418, body: '<html><head><title>I am a teapot</title></head></html>' })
    expect(v).toMatchObject({ status: 'error', kind: 'unexpected' })
    expect(v.reason).toBe('Unexpected answer (HTTP 418): “I am a teapot”')
    expect(classifyFetch({ status: 400, body: '' }).reason).toBe('Unexpected answer (HTTP 400): “(empty page)”')
  })
})
